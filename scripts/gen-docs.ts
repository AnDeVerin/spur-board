import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import {
  ERRORS,
  EXIT_CODES,
  OPERATIONS,
  SECRET_ENV_KEYS,
  configJsonSchema,
} from '../packages/contracts/src/index.ts';
import { createProgram, exampleCommand } from '../packages/cli/src/cli.ts';

const cliTarget = fileURLToPath(new URL('../docs/cli.md', import.meta.url));
const configTarget = fileURLToPath(new URL('../docs/configuration.md', import.meta.url));
const binarySource = readFileSync(new URL('../packages/cli/src/bin.mjs', import.meta.url), 'utf8');
const program = createProgram({ io: { isTTY: false, stdout: () => {}, stderr: () => {} } });
type CliCommand = ReturnType<typeof createProgram>;
const operationByCommand = new Map(
  OPERATIONS.map((operation) => [operation.cli.command, operation]),
);

interface SchemaNode {
  type?: string;
  description?: string;
  properties?: Record<string, SchemaNode>;
  required?: string[];
  items?: SchemaNode;
  oneOf?: SchemaNode[];
  const?: string;
  enum?: string[];
  default?: unknown;
  minItems?: number;
  minLength?: number;
  minimum?: number;
  maximum?: number;
  pattern?: string;
  format?: string;
  additionalProperties?: boolean;
}

function markdown(value: unknown): string {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

/** Direct routes in bin.mjs run before Commander. */
export function binaryRoutes(source = binarySource): string[] {
  const routes: string[] = [];
  for (const match of source.matchAll(
    /(?:^|\n)(?:if|} else if) \(argv\.length === 1 && ([^\n]+)\) \{/g,
  )) {
    for (const route of match[1]?.matchAll(/argv\[0\] === '([^']+)'/g) ?? []) {
      if (route[1] !== undefined) routes.push(route[1]);
    }
  }
  return routes;
}

export function registeredCommands(
  root: CliCommand = program,
): { path: string; command: CliCommand }[] {
  const visit = (command: CliCommand, path: string): { path: string; command: CliCommand }[] => [
    ...(path && (command.commands.length === 0 || operationByCommand.has(path))
      ? [{ path, command }]
      : []),
    ...command.commands.flatMap((child) =>
      visit(child, path ? `${path} ${child.name()}` : child.name()),
    ),
  ];
  return visit(root, '');
}

function setupExample(path: string, command: CliCommand): string {
  const required = command.options
    .filter((option) => option.required)
    .map((option) => option.flags)
    .join(' ');
  return `board ${path}${required ? ` ${required}` : ''}`;
}

export function renderCliDocs(): string {
  const lines = [
    '# CLI reference',
    '',
    '<!-- Generated by `pnpm gen`. Edit the command catalog or CLI registration instead. -->',
    '',
    'Use `board <command> --help` for interactive help. `--json` is available globally and on catalog operations; direct binary routes accept no extra arguments.',
    '',
    '## Exit codes',
    '',
    '| Code | Meaning |',
    '| --- | --- |',
    `| ${String(EXIT_CODES.ok)} | Success. |`,
    `| ${String(EXIT_CODES.refused)} | Refused or a blocking doctor check. |`,
    `| ${String(EXIT_CODES.usage)} | Invalid command, arguments, or flags. |`,
    `| ${String(EXIT_CODES.notApplied)} | A dependency prevented the action; it did not apply. |`,
    `| ${String(EXIT_CODES.config)} | Configuration or installation failure. |`,
    `| ${String(EXIT_CODES.outcomeUnknown)} | The action may have applied; inspect the result before retrying with the same key. |`,
    '',
    '## Commands',
    '',
  ];
  for (const { path, command } of registeredCommands()) {
    const operation = operationByCommand.get(path);
    const argumentsText = command.registeredArguments
      .map((arg) => (arg.required ? `<${arg.name()}>` : `[${arg.name()}]`))
      .join(' ');
    const flags = command.options
      .map((option) => `\`${option.flags}\` — ${option.description}`)
      .join('\n');
    const example = operation
      ? `${exampleCommand(operation, operation.examples[0].input)}${operation.kind === 'mutation' ? ` --key ${path.replaceAll(' ', '-')}-PROJ-123-example-1432` : ''}`
      : setupExample(path, command);
    lines.push(
      `### \`board ${path}\``,
      '',
      command.description() || operation?.description || '',
      '',
      `Arguments: ${argumentsText ? `\`${argumentsText}\`` : 'none'}.`,
      '',
      'Flags:',
      '',
      flags || 'None.',
      '',
      `Example: \`${example}\``,
      '',
    );
    if (operation) {
      lines.push(
        `Operation errors: ${operation.errors.map((code) => `\`${code}\` (exit ${String(ERRORS[code].exit)}: ${ERRORS[code].hint})`).join('; ')}.`,
        '',
      );
    } else {
      lines.push('Exit codes: see the table above; setup errors are reported by the CLI.', '');
    }
  }
  for (const route of binaryRoutes()) {
    const detail =
      route === 'mcp'
        ? 'Start the MCP server on standard input and output.'
        : 'Print the installed package version.';
    lines.push(
      `### \`board ${route}\``,
      '',
      detail,
      '',
      'Flags: none.',
      '',
      `Example: \`board ${route}\``,
      '',
      'Exit codes: 0 on success; startup errors are reported by the process.',
      '',
    );
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function constraints(node: SchemaNode): string {
  return (
    [
      node.enum ? `one of ${node.enum.join(', ')}` : undefined,
      node.const ? `must be ${node.const}` : undefined,
      node.format ? `format ${node.format}` : undefined,
      node.pattern ? `pattern ${node.pattern}` : undefined,
      node.minLength !== undefined ? `min length ${String(node.minLength)}` : undefined,
      node.minItems !== undefined ? `min items ${String(node.minItems)}` : undefined,
      node.minimum !== undefined ? `min ${String(node.minimum)}` : undefined,
      node.maximum !== undefined ? `max ${String(node.maximum)}` : undefined,
    ]
      .filter(Boolean)
      .join('; ') || '—'
  );
}

function schemaRows(root: SchemaNode): string[] {
  const rows: string[] = [];
  function visit(node: SchemaNode, path: string, required: boolean, variant = ''): void {
    if (node.oneOf) {
      for (const choice of node.oneOf) {
        const label = choice.properties?.['type']?.const ?? 'variant';
        visit(choice, path, required, label);
      }
      return;
    }
    if (path) {
      const label = variant ? `${path} (${variant})` : path;
      const fallback =
        node.default === undefined ? '—' : `\`${markdown(JSON.stringify(node.default))}\``;
      rows.push(
        `| \`${markdown(label)}\` | ${node.type ?? 'object'} | ${required ? 'yes' : 'no'} | ${fallback} | ${markdown(constraints(node))} | ${markdown(node.description ?? '—')} |`,
      );
    }
    for (const [name, child] of Object.entries(node.properties ?? {}))
      visit(
        child,
        path ? `${path}.${name}` : name,
        node.required?.includes(name) ?? false,
        variant,
      );
    if (node.items) visit(node.items, `${path}[]`, required, variant);
  }
  visit(root, '', true);
  return rows;
}

