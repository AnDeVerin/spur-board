export function renderConfigurationDocs(): string {
  const schema = configJsonSchema() as SchemaNode;
  return [
    '# Configuration reference',
    '',
    '<!-- Generated by `pnpm gen`. Edit the config schema or secret metadata instead. -->',
    '',
    '`config.yaml` is validated by the [JSON Schema](../packages/contracts/config.schema.json). Paths below use `[]` for array entries. Required means required in that object; defaults may fill optional fields.',
    '',
    'The JSON Schema cannot express every cross-field rule. Run `board doctor --offline` after editing the file.',
    '',
    '## config.yaml fields',
    '',
    '| Path | Type | Required | Default | Constraints | Description |',
    '| --- | --- | --- | --- | --- | --- |',
    ...schemaRows(schema),
    '',
    ...SESSION_LINKS,
    '',
    '## secrets.env keys',
    '',
    'Keep `secrets.env` private with mode `0600`. It lives beside `config.yaml` in the Board config directory, or under `BOARD_HOME` when set. Never put secret values in `config.yaml` or logs.',
    '',
    '| Key | Required when | Purpose |',
    '| --- | --- | --- |',
    ...SECRET_ENV_KEYS.map(
      ({ name, requiredWhen, purpose }) => `| \`${name}\` | ${requiredWhen} | ${purpose} |`,
    ),
    '',
  ].join('\n');
}

export async function formattedDocs(): Promise<{ cli: string; configuration: string }> {
  const [cliOptions, configOptions] = await Promise.all([
    resolveConfig(cliTarget),
    resolveConfig(configTarget),
  ]);
  return {
    cli: await format(renderCliDocs(), { ...cliOptions, parser: 'markdown' }),
    configuration: await format(renderConfigurationDocs(), {
      ...configOptions,
      parser: 'markdown',
    }),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const docs = await formattedDocs();
  writeFileSync(cliTarget, docs.cli);
  writeFileSync(configTarget, docs.configuration);
  console.log('wrote docs/cli.md and docs/configuration.md');
}
